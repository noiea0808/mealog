/**
 * 음식 사전 — 한 음식에 라벨 두 개 (형태 · 요리 종류)
 * (docs/entry-axes-and-tags-direction.md §5)
 *
 * ## 왜 구조를 뒤집었나
 *
 * 예전 사전은 `카테고리 → 키워드 목록` 이라 한 음식이 한 축에만 속했다. 그래서
 * 축 이름에 세 가지 기준(형태·식단컨셉·식품군)이 섞였고, "탕수육은 밥/한상인가
 * 단백질식인가" 같은 답 없는 질문이 생겼다. 실측에서 흔한 음식 59개 중 22%가
 * 미분류였고(치킨·돈까스·초밥·회…), 같은 돼지고기인데 삼겹살은 밥/한상,
 * 보쌈은 단백질식으로 갈렸다.
 *
 * 이제는 `음식 → { form, cuisine }` 한 항목이다:
 *   - **형태(form)**: 사용자가 고르는 주 축. 단일 기준이라 새 음식도 어디 넣을지 명확하다.
 *   - **요리 종류(cuisine)**: 음식 이름에서 기계적으로 도출되는 사실이라 **묻지 않고
 *     자동으로** 붙인다 (placeType·categoryAuto 와 같은 사실-유도 패턴).
 *
 * 부수 효과로 부분문자열 오탐이 사라진다. 예전엔 '탕수육' 이 단백질식 키워드 '수육' 에
 * 걸려 오분류됐는데, 이제 '탕수육' 자체가 한 항목이고 **최장 일치**를 쓰므로
 * 더 긴 이름이 항상 이긴다.
 *
 * ## 사전 관리 기준
 * 1. 실데이터에 반복 관측되는 음식만 추가한다
 * 2. 형태는 "이 음식의 주된 몸통이 무엇인가"로 정한다 (탕수육=고기, 짜장면=면)
 * 3. 요리 종류가 애매하면 '기타' 로 두고 형태만 채운다 — 억지로 넣지 않는다
 */

