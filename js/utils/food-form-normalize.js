/**
 * 형태(무엇을) 축 표기 정규화 — 분석 전용
 * (docs/entry-axes-and-tags-direction.md §5)
 *
 * 배경: 음식 사전을 재설계하면서 형태 축 이름이 바뀌었다(밥/한상→밥류, 단백질식→고기·생선…).
 * 그런데 `categoryAuto` 는 서버 backfill(classifyMoments)이 **시점에 따라 다른 축으로**
 * 채워 넣는다. 재배포 이전 기록은 옛 축, 이후는 새 축이고, `categorySource` 가 한 번
 * 찍힌 기록은 다시 분류되지 않으므로 저절로 정리되지 않는다.
 *
 * 원칙은 place-normalize.js 와 같다:
 *
 *   ### 저장된 원문은 절대 바꾸지 않는다. 정규화는 읽을 때만 한다.
 *
 * 마이그레이션 없이 차트에서만 두 축을 합친다. 매핑하지 않으면 옛 축 값이 새 축
 * 화이트리스트 밖으로 밀려 '미입력'으로 접힌다.
 *
 * 사용자가 직접 고른 축(userSettings.tags.category — 한식/양식/일식…)은 **건드리지 않는다.**
 * 그건 사용자 어휘이고, 옛 형태 축과는 다른 축이다.
 */

/** 옛 형태 축 → 새 형태 축. 1:1 대응이라 정보 손실이 없다 */
const LEGACY_FORM_MAP = new Map([
    // 운영에 남아 있는 첫 자동 분류 축
    ['밥/한상', '밥류'],
    ['단백질식', '고기·생선'],
    ['면', '면류'],
    ['빵/샌드위치', '빵류'],
    ['샐러드', '채소·샐러드'],
    ['커피/음료', '차/음료'],
    ['간식/디저트', '과자/스낵'],
    ['과일', '과일/견과'],
    // 형태 축이 간식 축을 흡수하기 전의 중간 값 (test 브랜치에서만 쓰였다)
    ['음료', '차/음료'],
    ['간식·디저트', '과자/스낵'],
]);

/**
 * 형태 축 값을 현재 축 표기로 맞춘다. 대상이 아니면 원문 그대로 돌려준다
 * (사용자 태그 '한식'·'양식' 등은 그대로 통과 — 다른 축이다).
 * @param {string|null|undefined} raw
 * @returns {string}
 */
export function normalizeFoodForm(raw) {
    const t = String(raw || '').trim();
    if (!t) return '';
    return LEGACY_FORM_MAP.get(t) || t;
}
